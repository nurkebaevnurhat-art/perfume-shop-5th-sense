/* ---------- Юридические страницы ----------
   Черновики для интернет-магазина в Республике Казахстан. Перед запуском:
   заполните реквизиты в FS.config.seller и покажите тексты юристу.
   Значения в квадратных скобках выделяются на странице как незаполненные. */
FS.legal = (function () {
  const { esc } = FS.ui;
  // Заготовка вида «[...]» подсвечивается, чтобы её было видно до замены.
  const fill = (v) => (/^\[.*\]$/.test(String(v)) ? `<mark class="fill">${esc(v)}</mark>` : esc(v));
  const seller = () => FS.config.seller;
  const shop = () => `интернет-магазин ${esc(FS.config.brand)} ${esc(FS.config.tagline)}`;

  function requisites() {
    const s = seller();
    return `<dl class="info-list">
        <div><dt>Продавец</dt><dd>${fill(s.name)}</dd></div>
        <div><dt>ИИН / БИН</dt><dd>${fill(s.taxId)}</dd></div>
        <div><dt>Адрес</dt><dd>${fill(s.address)}</dd></div>
        <div><dt>Телефон</dt><dd><span class="selectable">${esc(s.phone)}</span></dd></div>
        <div><dt>Почта</dt><dd><span class="selectable">${esc(s.email)}</span></dd></div>
      </dl>`;
  }

  function page(title, lead, sections) {
    return `
      <section class="page-head">
        <nav class="crumbs" aria-label="Навигационная цепочка"><a href="#home">Главная</a><span aria-hidden="true">/</span><span aria-current="page">${esc(title)}</span></nav>
        <h1>${esc(title)}</h1>
        <p class="page-lead">${lead}</p>
      </section>
      <div class="page-body info legal">
        <p class="notice legal-draft"><strong>Черновик.</strong> Текст подготовлен как основа и не является юридической консультацией. Перед запуском магазина заполните выделенные поля и согласуйте документ с юристом.</p>
        ${sections.map(([h, body]) => `<section><h2>${h}</h2>${body}</section>`).join('')}
        <p class="legal-date">Редакция от ${esc(FS.config.legalUpdated)}</p>
      </div>`;
  }

  return { fill, seller, shop, requisites, page };
})();

