/* ---------- Условия заказа, политика конфиденциальности, возврат ----------
   Онлайн-оплаты нет (решение владельца): заказ на сайте — заявка, цену, наличие
   и оплату подтверждает менеджер. Поэтому вместо длинной оферты — короткие
   «Условия заказа». Реквизиты ИП не обязательны: если заполнить
   FS.config.seller.legalName, строка появится в контактах этих страниц. */
FS.legal = (function () {
  const { esc } = FS.ui;
  const brandName = () => `${esc(FS.config.brand)} ${esc(FS.config.tagline)}`;

  function requisites() {
    const c = FS.config.contacts;
    const legal = (FS.config.seller && FS.config.seller.legalName) || '';
    const rows = [
      ['Бутик', brandName()],
      legal && ['Продавец', esc(legal)],
      c.address && ['Адрес', esc(c.address)],
      c.hours && ['Часы работы', esc(c.hours)],
      c.phone && ['Телефон', `<span class="selectable">${esc(c.phone)}</span>`],
      c.manager && ['Менеджер, WhatsApp', `<span class="selectable">${esc(c.manager)}</span>`],
      c.email && ['Почта', `<span class="selectable">${esc(c.email)}</span>`]
    ].filter(Boolean);
    return `<dl class="info-list">${rows.map(([k, v]) => `<div><dt>${k}</dt><dd>${v}</dd></div>`).join('')}</dl>`;
  }

  function page(title, lead, sections) {
    return `
      <section class="page-head">
        <nav class="crumbs" aria-label="Навигационная цепочка"><a href="#home">Главная</a><span aria-hidden="true">/</span><span aria-current="page">${esc(title)}</span></nav>
        <h1>${esc(title)}</h1>
        <p class="page-lead">${lead}</p>
      </section>
      <div class="page-body info legal">
        ${sections.map(([h, body]) => `<section><h2>${h}</h2>${body}</section>`).join('')}
        <p class="legal-date">Редакция от ${esc(FS.config.legalUpdated)}</p>
      </div>`;
  }

  return { brandName, requisites, page };
})();

